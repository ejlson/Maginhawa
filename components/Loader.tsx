// TWO CURVES. One for opacity, one for the window, and they are different
// KINDS of thing — a cubic-bezier and a generated spring.
//
// OPACITY: EASE_OUT. y1 = 1 makes it near-exponential, delivering most of its
// output inside the first tenth of its duration. On a fade that is exactly
// right: a cross-fade 90% done early reads as decisive, and there is no
// position for the eye to track. On GEOMETRY it is a pop followed by a creep —
// measured, driving the window open on it put 21% of the total travel into
// 150ms and then 3% into the next 150ms. Board fade, veil and progress bar
// only, and nothing else, ever.
const EASE_OUT = [0.23, 1, 0.32, 1] as const;
