/**
 * One split-flap cell. While loading it cycles the whole alphabet on a loop;
 * once `settle` is true it stops the next time it reaches its target letter,
 * so the word locks in with a staggered cascade.
 */
function FlipLetter({
  final,
  settle,
  startDelay = 0,
  reduce = false,
  onLock,
}: {
  final: string;
  settle: boolean;
  startDelay?: number;
  reduce?: boolean;
  onLock?: () => void;
}) {
  const targetIdx = Math.max(0, ALPHABET.indexOf(final.toUpperCase()));
  const [idx, setIdx] = useState(reduce ? targetIdx : 0);
  const settleRef = useRef(settle);
  settleRef.current = settle;
  const lockedRef = useRef(false);
  const lock = () => {
    if (!lockedRef.current) {
      lockedRef.current = true;
      onLock?.();
    }
  };

  useEffect(() => {
    if (reduce) {
      setIdx(targetIdx);
      lock();
      return;
    }
    let i = 0;
    let timer: ReturnType<typeof setTimeout>;
    // each flap runs at its own pace, so they desync and lock in at
    // different moments like a real split-flap board
    const baseTick = FLIP_TICK * (0.78 + Math.random() * 0.7);
    const begin = startDelay + Math.random() * 160;

    const step = () => {
      i = (i + 1) % 26;
      if (settleRef.current && i === targetIdx) {
        setIdx(targetIdx); // reached its letter -> stop
        lock();
        return;
      }
      setIdx(i);
      // a little mechanical jitter on every flip
      timer = setTimeout(step, baseTick * (0.82 + Math.random() * 0.4));
    };

    const start = setTimeout(step, begin);
    return () => {
      clearTimeout(start);
      clearTimeout(timer);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [reduce, targetIdx, startDelay]);

  const ch = ALPHABET[idx];
  return (
    <span className={styles.flip}>
      <motion.span
        key={ch}
        className={styles.flipInner}
        initial={{
          transform: reduce ? "rotateX(0deg)" : "rotateX(-78deg)",
          opacity: reduce ? 1 : 0.4,
        }}
        animate={{ transform: "rotateX(0deg)", opacity: 1 }}
        transition={{ duration: 0.16, ease: [0.2, 0.7, 0.3, 1] }}
      >
        {ch}
      </motion.span>
    </span>
  );
}

/**
 * Loading screen + intro:
 *  stage 0 — split-flap board scrambles while assets load; a progress bar at
 *            the bottom fills. When loading completes the letters lock to MGNHW.
 *  stage 1 — the board fades out in place; four cream shutters open a window
 *            from a ~3px point in the middle of the screen and the film SCALES
 *            UP INTO IT rather than being uncovered; it settles out to a size
 *            that can be looked at, holds dead still for 170ms, then springs
 *            to full bleed, revealing the video behind the cream
 *            overlay. The hero's own lockup arrives after the hand-off.
 *  stage 2 — hand off to the page (onDone).
 *
 * On a repeat visit (or with prefers-reduced-motion) the long choreography is
 * skipped: once assets are ready the cream overlay just cross-fades away.
 */
export default function Loader({
  insets,
  onDone,
}: {
  insets: HeroInsets;
  onDone: () => void;
}) {
  const [stage, setStage] = useState(0);
  const [vp, setVp] = useState<Vp | null>(null);
  const [progress, setProgress] = useState(0);
  const [ready, setReady] = useState(false);
  const [locked, setLocked] = useState(0);
  // false on both SSR and first client render so hydration matches; an effect
  // reads sessionStorage afterwards and may flip this for the short path.
  const [seen, setSeen] = useState(false);
  // resolved on the client (after mount) so we never touch window during render
  const [reduce, setReduce] = useState(false);
  const [faded, setFaded] = useState(false); // drives the short-path cross-fade
  const doneRef = useRef(false);
  // top, bottom, left, right — the order playIntroWindow() reads them in.
  const shutters = useRef<(HTMLDivElement | null)[]>([null, null, null, null]);

  const callDone = () => {
    if (!doneRef.current) {
      doneRef.current = true;
      // The hero OWNS the film's zoom wrapper; the loader only borrows it for
      // the reveal. Releasing here — rather than in the stage-1 effect — means
      // the SAFETY_CAP backstop and the short path get the same cleanup as the
      // normal exit, and the hero is never left carrying a forwards-filling
      // animation (and a promoted full-viewport layer) for the session.
      releaseIntroFilm();
      onDone();
    }
  };

  // Fail-safe: under no circumstances may the loader permanently block the page.
  // Independent of path, asset signals, or any per-stage effect, force the
  // hand-off at SAFETY_CAP. The doneRef guard above dedupes against the normal
  // exits, so this can only ever fire if something unforeseen stalled them.
  useEffect(() => {
    const safety = setTimeout(callDone, SAFETY_CAP);
    return () => clearTimeout(safety);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useEffect(() => {
    setVp({ w: window.innerWidth, h: window.innerHeight });
    setReduce(window.matchMedia("(prefers-reduced-motion: reduce)").matches);
    // mark the intro as seen for next time; reading is wrapped for privacy mode
    try {
      if (sessionStorage.getItem(SEEN_KEY) === "1") setSeen(true);
      sessionStorage.setItem(SEEN_KEY, "1");
    } catch {
      /* sessionStorage unavailable (privacy mode / quota) — treat as first visit */
    }
  }, []);

  // reduced motion forces the short path regardless of session state
  const shortPath = reduce || seen;

  // Drive loading progress from real asset signals + a minimum display time.
  useEffect(() => {
    let cancelled = false;
    let assetsDone = false;
    let minDone = false;
    const finish = () => {
      if (assetsDone && minDone && !cancelled) {
        setProgress(100);
        setReady(true);
      }
    };

    // trickle up to ~90% so the bar always feels alive
    const trickle = setInterval(() => {
      setProgress((p) => (p < 90 ? Math.min(90, p + (p < 55 ? 3 : 1.4)) : p));
    }, 130);

    const minT = setTimeout(
      () => {
        minDone = true;
        finish();
      },
      shortPath ? MIN_TIME_REPEAT : MIN_TIME,
    );

    // wait on fonts + the hero video being playable
    let pending = 0;
    const done = () => {
      pending -= 1;
      if (pending <= 0) {
        assetsDone = true;
        finish();
      }
    };
    const cleanups: Array<() => void> = [];

    pending += 1;
    (document.fonts?.ready ?? Promise.resolve()).then(done);

    pending += 1;
    // the hero <video> may not have mounted yet when this effect runs —
    // poll a short window before concluding there is none
    const searchStart = performance.now();
    let raf = 0;
    const findVideo = () => {
      const v = document.querySelector("video");
      if (v) {
        if (v.readyState >= 3) done();
        else {
          const h = () => done();
          v.addEventListener("canplay", h, { once: true });
          cleanups.push(() => v.removeEventListener("canplay", h));
        }
        return;
      }
      if (performance.now() - searchStart < VIDEO_WAIT) {
        raf = requestAnimationFrame(findVideo);
      } else {
        done();
      }
    };
    raf = requestAnimationFrame(findVideo);
    cleanups.push(() => cancelAnimationFrame(raf));

    const cap = setTimeout(() => {
      assetsDone = true;
      minDone = true;
      finish();
    }, HARD_CAP);

    return () => {
      cancelled = true;
      clearInterval(trickle);
      clearTimeout(minT);
      clearTimeout(cap);
      cleanups.forEach((f) => f());
    };
  }, [shortPath]);

  // short path: once ready, cross-fade the cream overlay away then hand off
  useEffect(() => {
    if (!shortPath || !ready) return;
    setFaded(true);
    const t = setTimeout(callDone, FADE_MS);
    return () => clearTimeout(t);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [shortPath, ready]);

  // full path: start the split once every flap has locked in (or a cap elapses)
  useEffect(() => {
    if (shortPath || !ready) return;
    const allLocked = locked >= LETTERS.length;
    const t = setTimeout(() => {
      // Aim the hero film at the one shot that can carry the whole reveal —
      // see HERO_SEEK_S's note for the cut map and why neither 0 nor the
      // 6.00 keyframe will do. 5.84 is NOT a keyframe (nearest IDR 4.68):
      // the ~29 P-frame decode costs ~8ms, measured, and it happens here,
      // BEFORE stage 1's first animated frame, without dropping readyState.
      // Buffer-guarded so a cold cache degrades to the head of the clip —
      // yesterday's behaviour — rather than a blank window on unbuffered
      // film.
      const v = document.querySelector("video");
      if (v && v.readyState >= 2) {
        let buffered = false;
        for (let i = 0; i < v.buffered.length; i++)
          if (
            v.buffered.start(i) <= HERO_SEEK_S &&
            HERO_SEEK_S < v.buffered.end(i)
          )
            buffered = true;
        try {
          v.currentTime = buffered ? HERO_SEEK_S : 0;
        } catch {
          /* seek refused — the film simply keeps its current position */
        }
      }
      setStage(1);
    }, allLocked ? 380 : SETTLE_CAP);
    return () => clearTimeout(t);
  }, [shortPath, ready, locked]);

  // ── THE REVEAL ITSELF ──
  // Stage 1 hands the whole window to lib/introWindow.ts: four cream shutters
  // and the hero's film, all started from THIS ONE CALL with one explicit
  // `startTime`, all on `transform`, all on the compositor. No piece of the
  // geometry is computed twice — see that module for why `k` is the only
  // number here, and for the two mechanisms that were built, measured and
  // rejected before it.
  //
  // WHY AN EFFECT AND NOT A `motion` PROP. The film lives in <Hero>, this
  // component's SIBLING, so it can only be reached imperatively through the
  // registry — and the shutters have to share the film's clock exactly or a
  // seam of hero background opens along the aperture edge. One imperative call
  // site is the only way all five get the same start time.
  useEffect(() => {
    if (shortPath || stage !== 1 || !vp) return;
    // The point of light as a FRACTION of the viewport, so `k` can be driven
    // straight from it. SEED_PX_MIN is absolute on purpose — see its note.
    const kPoint = SEED_PX_MIN / vp.w;
    // The hold's size as a fraction, under the same clamp its px constants
    // describe, so `k` can be driven straight from it at any viewport.
    const kHold =
      Math.min(Math.max(HOLD_MIN_PX, vp.w * HOLD_VW), vp.w * HOLD_MAX_VW) /
      vp.w;
    const anim = playIntroWindow({
      // FIVE KEYFRAMES, THREE OF WHICH ARE STILL. The first pair holds the
      // point under the veil; the middle pair IS the hold, and because both
      // carry the identical value the interpolation between them is exactly
      // still — no sub-pixel drift is even representable. The head exists
      // because the reveal's clock has to be REVEAL_MS long: every probe in
      // scripts/ identifies this animation by its duration, and a `delay`
      // would have made the animation's own currentTime disagree with the
      // timeline everything else is graded on.
      k: [kPoint, kPoint, kHold, kHold, 1],
      times: [0, T_WIN_OPEN, T_HOLD_IN, T_HOLD_OUT, REVEAL_MS].map(
        (t) => t / REVEAL_MS,
      ),
      ease: [HOLD, EASE_SETTLE, HOLD, SPRING_OUT],
      duration: REVEAL_MS,
      shutters: shutters.current,
      endInset: {
        top: insets.top / vp.h,
        bottom: insets.bottom / vp.h,
        side: insets.side / vp.w,
      },
    });
    // No elements means no reveal, and a loader that never finishes is worse
    // than one that cuts: fall straight through to the hand-off.
    if (!anim) {
      setStage(2);
      return;
    }
    let live = true;
    anim.finished.then(() => live && setStage(2)).catch(() => {});
    // Deliberately NOT cancelled on cleanup: the shutters must hold their final
    // `scale(0)` (and the film its identity) until the overlay unmounts
    // HANDOFF_MS later. callDone() is what releases the film.
    return () => {
      live = false;
    };
  }, [shortPath, stage, vp, insets]);

  // Full path: after the window has grown, hand control back to the page. The
  // insets are all zero, so the window is already full-bleed when the reveal
  // completes — there is no residual cream to cross-fade, and the old 540ms
  // hold here was half a second of a finished, frozen frame. HANDOFF_MS is
  // only a paint buffer; callDone stays idempotent via doneRef, and the
  // SAFETY_CAP failsafe above is untouched.
  useEffect(() => {
    if (stage !== 2) return;
    const t = setTimeout(callDone, HANDOFF_MS);
    return () => clearTimeout(t);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [stage]);

  if (!vp)
    return (
      <div
        className={styles.overlay}
        /* ⚠️ THE LOADER IS A CREAM SHEET AT z-index 100 COVERING THE WHOLE
             VIEWPORT, AND ONLY SCRIPT DISMISSES IT. With JavaScript off it
             stands for ever: measured, the home page was a blank cream
             screen with the entire site correctly laid out underneath it.
             The <noscript> block in app/layout.tsx removes it — an intro
             animation that cannot play should not be a lid. */
        data-nojs-hide=""
        style={{ background: "var(--cream)" }}
        aria-hidden
      />
    );

  // ---- short path: just a cream overlay that cross-fades out ----------------
  if (shortPath) {
    return (
      <div className={styles.overlay} aria-hidden data-nojs-hide="">
        <motion.div
          className={styles.sheet}
          initial={{ opacity: 1 }}
          animate={{ opacity: faded ? 0 : 1 }}
          transition={{ duration: FADE_MS / 1000, ease: SMOOTH }}
        />
        <motion.div
          className={styles.progress}
          animate={{ opacity: faded ? 0 : 1 }}
          transition={{ duration: 0.3 }}
        >
          <div
            className={styles.bar}
            style={{ transform: `scaleX(${progress / 100})` }}
          />
          <span className={styles.count}>
          {Math.min(100, Math.round(progress))}
        </span>
        </motion.div>
      </div>
    );
  }

  // ---- full path: split-flap board + the four-shutter window ----------------
  // NOTHING IS COMPUTED HERE ANY MORE. This block used to build five
  // `clip-path: path()` strings and their `times` and per-segment easing
  // arrays, on every render of every stage. The window is one scalar on one
  // spring now, and the only place that needs it is the effect above, so the
  // render path is just markup.


  const lockInc = () => setLocked((n) => n + 1);

  return (
    <div className={styles.overlay} aria-hidden data-nojs-hide="">
      {/* ═══ THE WINDOW: FOUR CREAM SHUTTERS ═══
          Each is a FULL-VIEWPORT cream sheet anchored to one edge by its
          transform-origin, and each scales by exactly the same value —
          (1 − k) / 2 — because the aperture is centred and uniform. Together
          they leave a k·vw × k·vh hole in the middle of the screen, and the
          hero's film scales by that same k to fill it. See lib/introWindow.ts.

          THEY REPLACE A SINGLE `clip-path: path()` SHEET, which was not
          compositor-accelerated: 7.4‥8.2ms of paint on EVERY displayed frame
          against full-viewport paint records, ~1261 RasterTasks over the
          grow-out, 8 of 97 frames compositor-animated — and the film frozen at
          natural size behind it the whole time, which is why the reveal
          uncovered a picture instead of zooming one. These four animate
          `transform` and nothing else.

          THE INLINE TRANSFORM IS NOT DECORATION AND IT IS NOT REDUNDANT WITH
          THE ANIMATION. `scaleY(0.5)` / `scaleX(0.5)` IS k = 0, the shut
          state, and carrying it (with `will-change: transform` from the
          stylesheet) on the FIRST render of stage 0 is what promotes these
          layers during the 2.6s of split-flap idle. Promoting them at
          animation start instead measured a 100‑137ms hitch on every run —
          five new full-viewport layers built inside one frame. Do not
          "simplify" this to a bare div plus an animation. */}
      {SHUTTERS.map(({ cls, axis }, i) => (
        <div
          key={cls}
          ref={(el) => {
            shutters.current[i] = el;
          }}
          className={`${styles.shutter} ${styles[cls]}`}
          style={{ transform: `${axis}(0.5)` }}
        />
      ))}

      {/* THE VEIL, AND IT IS WHY THE FILM DOES NOT APPEAR FROM NOTHING.
          An unclipped cream sheet over the whole viewport, so it is invisible
          against the cream overlay and only ever veils what shows THROUGH the
          window. It holds until 260ms — by which point the window is already
          a ~3px point — then fades over 120ms. EASE_OUT is near-expo, so
          although it nominally ends at 320ms it is under 5% opacity within
          ~50ms of starting. Its whole job is that a point of light should
          MATERIALISE rather than hard-pop; it deliberately does NOT last long
          enough to be a reveal of its own, because the reader should be
          watching the dot grow, not watching a cream sheet clear.
          It must sit ABOVE the shutters and BELOW .letters: veiling the board
          would hide the very letters that are fading out underneath it. */}
      <motion.div
        className={styles.veil}
        initial={{ opacity: 1 }}
        animate={{ opacity: stage >= 1 ? 0 : 1 }}
        transition={
          stage >= 1
            ? { duration: VEIL_FADE_S, delay: VEIL_DELAY_S, ease: EASE_OUT }
            : { duration: 0 }
        }
      />

      {/* The board leaves in place. It does not travel, so no frame can catch
          a legible letter on a screen edge; it recedes 4% so the exit reads as
          a departure rather than a bulb going out. */}
      <motion.div
        className={styles.letters}
        initial={{ opacity: 1, scale: 1 }}
        animate={
          stage === 0
            ? { opacity: 1, scale: 1 }
            : { opacity: 0, scale: BOARD_RECEDE }
        }
        transition={
          stage === 0
            ? { duration: 0.4, ease: SMOOTH }
            : { duration: BOARD_FADE_S, ease: EASE_OUT }
        }
      >
        <span className={styles.board}>
          {LETTERS.map((ch, i) => (
            <FlipLetter
              key={i}
              final={ch}
              settle={ready}
              startDelay={i * 55}
              reduce={false}
              onLock={lockInc}
            />
          ))}
        </span>
      </motion.div>

      <motion.div
        className={styles.progress}
        animate={{ opacity: stage >= 1 ? 0 : 1 }}
        transition={{ duration: 0.25, ease: EASE_OUT }}
      >
        <div
          className={styles.bar}
          style={{ transform: `scaleX(${progress / 100})` }}
        />
        <span className={styles.count}>
          {Math.min(100, Math.round(progress))}
        </span>
      </motion.div>
    </div>
  );
}
