// THE WINDOW: A SPRING, AND IT IS THE ONLY CURVE THE GEOMETRY TOUCHES.
// Generated by Motion's own spring solver at perceptual duration 0.9s,
// bounce 0.12 — a 0.23% overshoot (k peaks at 1.0023), enough to feel alive
// and far too small to read as a bounce. It is a `linear()` easing with 37
// control points because that is the only CSS easing that can express a
// spring; no cubic-bezier approximates one, which is the whole reason the
// bezier era below ended.
//
// ⚠️ IT IS A STRING AND IT GOES STRAIGHT TO `element.animate()`. Do not
// "convert" it to a tuple, and do not hand it to a framer `transition` — see
// lib/introWindow.ts on why a MotionValue is never accelerated. `linear()` is
// supported by WAAPI and Chrome keeps such a transform animation on the
// compositor: VERIFIED, 0 RasterTasks and 0.0ms of paint across the whole
// expansion. If a browser ever rejects the string, `element.animate()` throws
// rather than falling back, which is what we want — a silent fallback would
// put five layers on five different curves.
//
// ── WHAT THIS REPLACED, SO THAT NOBODY REBUILDS IT ──
// The window used to open in FOUR segments: a closed head, an ease-out open to
// 86% of a "postcard" size, a linear pass ACROSS that postcard, and an
// ease-in-out grow-out. That staging was never in the brief; it was invented
// to fix a stall and it is what made the reveal read as staged rather than as
// one expansion. Its constants (WIN_IN, WIN_OUT, EASE_WINDOW, EASE_MORPH,
// LINEAR, T_POST_IN, T_POST_OUT) are all deleted.
// Two findings from that era are still worth keeping, because they are about
// JOINS and any future multi-segment timeline will hit them again:
//   • an iOS sheet ENTRANCE curve on a morph — EASE_DRAWER [0.32, 0.72, 0, 1]
//     — put 60% of the window's travel into one 200ms burst, and with x2 = 0
//     its tail flattened so far out that the last 250ms carried 1.2% of the
//     travel. Category error, not a tuning miss.
//   • a curve with y1 = 0 starts at EXACTLY zero velocity, so handing it a
//     segment that is already moving costs a measured hesitation: 8‥11px of
//     travel in the 40ms tick after the join against 24px before it.
// A spring has one segment and no joins, so neither can happen here — which is
// the strongest argument for it after the shape itself.
// SEGMENT A — the point settles out to the hold. REST TO REST, so ease-in-out
// is the correct category and easeInOutCubic is the plain choice. Its gentle
// start is the entire reason this segment exists rather than a spring: a
// front-loaded curve had the aperture past 100px within ~50ms of becoming
// visible, so the small phase registered rather than read.
const EASE_SETTLE = "cubic-bezier(0.65, 0, 0.35, 1)";

// SEGMENT B — the hold releases to full bleed. STARTS FROM REST, which is what
// a spring models, so a spring is right here and only here. Generated by
// Motion's solver at perceptual duration 0.6s, bounce 0.12 — it solves to
// 750ms and it is GIVEN 750ms (see T_HOLD_OUT → REVEAL_MS), so the curve runs
// at the duration it was solved for rather than being time-compressed into a
// rounder slot. Peak overshoot 1.0028.
